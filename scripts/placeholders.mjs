// Lists every [[placeholder]] in content/ and src/config/site.ts and rewrites PLACEHOLDERS.md.
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const targets = ["content", "src/config/site.ts"];

function walk(p) {
  const abs = path.join(root, p);
  if (fs.statSync(abs).isDirectory()) {
    return fs.readdirSync(abs).sort().flatMap((f) => walk(path.posix.join(p, f)));
  }
  return /\.(md|mdx|ts)$/.test(p) ? [p] : [];
}

const lines = [];
for (const file of targets.flatMap(walk)) {
  fs.readFileSync(path.join(root, file), "utf8")
    .split(/\r?\n/)
    .forEach((line, i) => {
      if (line.includes("[[")) lines.push(`- ${file}:${i + 1} — ${line.trim()}`);
    });
}

const header = `# Placeholders

This file is regenerated by \`pnpm placeholders\`. Every \`[[...]]\` string in \`content/\` and \`src/config/site.ts\` is listed below. Replace each one with confirmed client details; in production builds the brackets are stripped, so unresolved placeholders ship as plain text.

`;
fs.writeFileSync(path.join(root, "PLACEHOLDERS.md"), `${header}${lines.join("\n")}\n`);
console.log(lines.join("\n"));
console.log(`\n${lines.length} placeholder lines. PLACEHOLDERS.md updated.`);
